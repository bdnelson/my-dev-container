#!/usr/bin/env bash
# Regenerate requirements.txt (hash-pinned) for the Python-based DB clients.
#
# Runs uv inside a Linux container so the resolution matches the image we build,
# not the workstation running this script. Output covers both amd64 and arm64
# via environment markers.

set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"

set -a
# shellcheck disable=SC1091
source versions.env
set +a

workdir="$repo_root/.uv-compile"
mkdir -p "$workdir"
trap 'rm -rf "$workdir"' EXIT

cat >"$workdir/requirements.in" <<EOF
pgcli==${PGCLI_VERSION}
mycli==${MYCLI_VERSION}
EOF

# Resolution is --universal, so it does not depend on the container's own
# architecture. Pin to the host's to avoid an emulated run, which is minutes
# slower than a native one.
case "$(uname -m)" in
  arm64|aarch64) platform=linux/arm64 ;;
  *)             platform=linux/amd64 ;;
esac

# Bind-mounts a directory inside the repo rather than a system temp path:
# Docker Desktop on macOS only shares a fixed set of host directories, and
# mktemp paths under /var/folders are not reliably among them.
# --output-file must be a real path in the mounted directory. uv writes it
# atomically via a rename, which hangs indefinitely against /dev/stdout.
docker run --rm --platform "$platform" \
  -v "$workdir:/in" \
  ghcr.io/astral-sh/uv:python3.13-trixie-slim \
  uv pip compile /in/requirements.in \
    --universal \
    --generate-hashes \
    --no-header \
    --quiet \
    --output-file /in/requirements.txt

cp "$workdir/requirements.txt" requirements.txt

{
  echo "# Generated by bin/update-requirements.sh. Do not edit by hand."
  echo "# Sourced from pgcli/mycli pins in versions.env."
  cat requirements.txt
} >requirements.txt.new
mv requirements.txt.new requirements.txt

echo "wrote $(grep -c '^[a-zA-Z]' requirements.txt) pinned packages to requirements.txt" >&2
