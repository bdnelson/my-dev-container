#!/usr/bin/env bash
# Regenerate checksums.txt from the versions pinned in versions.env.
#
# Downloads every release artifact for every supported architecture and records
# its SHA-256. The Dockerfile verifies downloads against this file, so a build
# fails loudly if an upstream artifact is replaced under an existing tag.
#
# This pins content, not provenance: the digest and the artifact both come from
# the same TLS origin.
#
# Usage: bin/update-versions.sh [tool ...]

set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"

set -a
# shellcheck disable=SC1091
source versions.env
set +a

# shellcheck disable=SC1091
source bin/artifacts.sh

if [ "$#" -gt 0 ]; then
  requested=("$@")
  TOOLS=()
  NOARCH_TOOLS=()
  for t in "${requested[@]}"; do
    if [ "$t" = nvm ]; then NOARCH_TOOLS+=("$t"); else TOOLS+=("$t"); fi
  done
fi

workdir=$(mktemp -d)
trap 'rm -rf "$workdir"' EXIT

out="$workdir/checksums.txt"
: >"$out"

record() {
  # record <tool> <arch>
  local tool=$1 arch=$2 id url sha
  id="${tool}-${arch}"
  url=$(artifact_url "$tool" "$arch")
  printf '  fetching %-24s %s\n' "$id" "$url" >&2
  curl -fsSL --retry 5 --retry-delay 2 --retry-all-errors -o "$workdir/$id" "$url"
  sha=$(sha256sum "$workdir/$id" | cut -d' ' -f1)
  echo "$sha  $id" >>"$out"
}

for tool in "${TOOLS[@]+"${TOOLS[@]}"}"; do
  for arch in "${ARCHES[@]}"; do
    record "$tool" "$arch"
  done
done

for tool in "${NOARCH_TOOLS[@]+"${NOARCH_TOOLS[@]}"}"; do
  record "$tool" noarch
done

if [ "$#" -gt 0 ] && [ -f checksums.txt ]; then
  # Partial refresh: keep entries for tools that were not requested.
  keep=$(mktemp)
  pattern=$(printf '%s\n' "$@" | sed 's/$/-/' | paste -sd'|' -)
  grep -Ev "  (${pattern})" checksums.txt >"$keep" || true
  cat "$keep" >>"$out"
  rm -f "$keep"
fi

{
  echo "# Generated by bin/update-versions.sh. Do not edit by hand."
  echo "# Regenerate after changing any version in versions.env."
  grep -v '^#' "$out" | sort -k2
} >checksums.txt

echo "wrote $(grep -cv '^#' checksums.txt) entries to checksums.txt" >&2
